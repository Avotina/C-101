#include <stdio.h>

int main(void) {
    int integer = 4;
    float floating_number = 13.32;
    char character ='H';

    printf("The integer value is: %d\n", integer);
    printf("The float value is: %f\n", floating_number);
    printf("The character value is: %c\n", character);

    return 0;
}
